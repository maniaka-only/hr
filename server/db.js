function normalizeParams(params) {
    if (params.length === 1 && Array.isArray(params[0])) {
        return params[0].map((p) => (p === undefined ? null : p))
    }
    return params.map((p) => (p === undefined ? null : p))
}

export const db = {
    prepare(sql) {
        return {
            get(...params) {
                const clean = normalizeParams(params)
                const stmt = database.prepare(sql)
                if (clean.length) stmt.bind(clean)
                if (stmt.step()) {
                    const cols = stmt.getColumnNames()
                    const vals = stmt.get()
                    stmt.free()
                    const row = {}
                    cols.forEach((c, i) => row[c] = vals[i])
                    return row
                }
                stmt.free()
                return undefined
            },
            all(...params) {
                const clean = normalizeParams(params)
                const results = []
                const stmt = database.prepare(sql)
                if (clean.length) stmt.bind(clean)
                while (stmt.step()) {
                    const cols = stmt.getColumnNames()
                    const vals = stmt.get()
                    const row = {}
                    cols.forEach((c, i) => row[c] = vals[i])
                    results.push(row)
                }
                stmt.free()
                return results
            },
            run(...params) {
                const clean = normalizeParams(params)
                database.run(sql, clean)
                const changes = database.getRowsModified()
                const lastIdResult = database.exec('SELECT last_insert_rowid() AS id')
                const lastInsertRowid = lastIdResult.length > 0 ? lastIdResult[0].values[0][0] : 0
                saveDb()
                return { changes, lastInsertRowid }
            }
        }
    },
    transaction(fn) {
        return (...args) => {
            inTransaction = true
            database.run('BEGIN TRANSACTION')
            try {
                fn(...args)
                database.run('COMMIT')
                inTransaction = false
                saveDb()
            } catch (e) {
                database.run('ROLLBACK')
                inTransaction = false
                throw e
            }
        }
    }
}

